const NC = CLASSES.length;
const uniforms = {
  uDetTex: { value: null as THREE.Texture | null },
  uDetLayer: { value: new Float32Array(NC) },
  uDetAmt: { value: new Float32Array(NC) },
  uDetScale: { value: new Float32Array(NC) },
  uDetGlobal: { value: 1 },
  uDetBump: { value: 1.6 },
  uDetCloud: { value: 0 },
  uDetMacro: { value: 0.12 },
  uDetTime: { value: 0 },
};

function neutralArray(): THREE.DataArrayTexture {
  const d = new Uint8Array(4 * LAYERS.length);
  for (let i = 0; i < LAYERS.length; i++) d.set([128, 128, 128, 255], i * 4);
  const t = new THREE.DataArrayTexture(d, 1, 1, LAYERS.length);
  t.needsUpdate = true;
  return t;
}
uniforms.uDetTex.value = neutralArray();

let loadedSize = 0;
/** Load the surface textures into one texture array (call once, before or after the first scene). */
export async function loadDetail(): Promise<void> {
  const g = gfx();
  if (g.surface === 0) return;
  const size = g.texSize;
  if (loadedSize === size) return;
  const dir = size >= 1024 ? 'tex/look' : 'tex/look512';
  const imgs = await Promise.all(
    LAYERS.map(
      (n) =>
        new Promise<HTMLImageElement | null>((res) => {
          const im = new Image();
          im.onload = () => res(im);
          im.onerror = () => res(null);
          im.src = `${dir}/${n}.jpg`;
        }),
    ),
  );
  const cv = document.createElement('canvas');
  cv.width = cv.height = size;
  const c = cv.getContext('2d', { willReadFrequently: true })!;
  const data = new Uint8Array(size * size * 4 * LAYERS.length);
  imgs.forEach((im, i) => {
    if (!im) {
      for (let k = 0; k < size * size; k++) data.set([128, 128, 128, 255], i * size * size * 4 + k * 4);
      return;
    }
    c.clearRect(0, 0, size, size);
    c.drawImage(im, 0, 0, size, size);
    data.set(c.getImageData(0, 0, size, size).data, i * size * size * 4);
  });
  const t = new THREE.DataArrayTexture(data, size, size, LAYERS.length);
  t.format = THREE.RGBAFormat;
  t.type = THREE.UnsignedByteType;
  t.wrapS = t.wrapT = THREE.RepeatWrapping;
  t.minFilter = THREE.LinearMipmapLinearFilter;
  t.magFilter = THREE.LinearFilter;
  t.generateMipmaps = true;
  t.anisotropy = 8;
  t.colorSpace = THREE.NoColorSpace;
  t.needsUpdate = true;
  uniforms.uDetTex.value = t;
  loadedSize = size;
}

export interface DetailMood {
  palette?: string | Partial<Palette>;
  /** 0..1 overall strength. */
  strength?: number;
  /** Drifting cloud shadows on the ground (outdoor daytime). */
  clouds?: number;
}

/** Set the palette for the view that is about to show. */
export function setDetailMood(m: DetailMood): void {
  const pal: Palette = { ...BASE, ...(typeof m.palette === 'string' ? PALETTES[m.palette] ?? {} : m.palette ?? {}) };
  CLASSES.forEach((c, i) => {
    const [layer, amt, scale] = pal[c];
    uniforms.uDetLayer.value[i] = L(layer);
    uniforms.uDetAmt.value[i] = amt;
    uniforms.uDetScale.value[i] = scale;
  });
  uniforms.uDetGlobal.value = m.strength ?? 1;
  uniforms.uDetCloud.value = m.clouds ?? 0;
}
setDetailMood({});

export function tickDetail(t: number): void {
  uniforms.uDetTime.value = t;
}

const VERT_HEAD = /* glsl */ `
varying vec3 vDetP;
varying vec3 vDetN;
varying vec3 vDetW;`;

const VERT_BODY = /* glsl */ `
{
  mat3 detM = mat3(modelMatrix);
  vec4 detW = vec4(position, 1.0);
  #ifdef USE_INSTANCING
    detM = detM * mat3(instanceMatrix);
    detW = instanceMatrix * detW;
  #endif
  vDetP = detM * position;
  vDetN = normalize(detM * objectNormal);
  vDetW = (modelMatrix * detW).xyz;
}`;

const FRAG_HEAD = /* glsl */ `
varying vec3 vDetP;
varying vec3 vDetN;
varying vec3 vDetW;
uniform highp sampler2DArray uDetTex;
uniform float uDetLayer[${NC}];
uniform float uDetAmt[${NC}];
uniform float uDetScale[${NC}];
uniform float uDetGlobal, uDetBump, uDetCloud, uDetMacro, uDetTime;
float detH = 0.5;
float detR = 0.5;
float detA = 0.0;
int detClass(vec3 c, float up) {
  float mx = max(c.r, max(c.g, c.b));
  float mn = min(c.r, min(c.g, c.b));
  float lum = dot(c, vec3(0.2126, 0.7152, 0.0722));
  float sat = (mx - mn) / (mx + 1e-4);
  if (lum < 0.012) return 10;
  if (sat < 0.2) {
    if (lum > 0.5) return up > 0.6 ? 7 : 8;
    return up > 0.6 ? 5 : 6;
  }
  float h;
  if (mx == c.r) h = mod((c.g - c.b) / (mx - mn + 1e-4), 6.0);
  else if (mx == c.g) h = (c.b - c.r) / (mx - mn + 1e-4) + 2.0;
  else h = (c.r - c.g) / (mx - mn + 1e-4) + 4.0;
  h *= 60.0;
  if (h > 65.0 && h < 175.0) return up > 0.6 ? 0 : 1;
  if (h >= 8.0 && h < 65.0) {
    if (lum < 0.2 && sat > 0.45) return 2;
    if (sat < 0.75) return up > 0.6 ? 3 : 4;
  }
  return 9;
}
vec3 detSample(vec3 p, float layer, vec3 w) {
  #if DET_LEVEL >= 2
    vec3 a = texture(uDetTex, vec3(p.zy, layer)).rgb;
    vec3 b = texture(uDetTex, vec3(p.xz, layer)).rgb;
    vec3 c = texture(uDetTex, vec3(p.xy, layer)).rgb;
    return a * w.x + b * w.y + c * w.z;
  #else
    vec2 uv = w.y >= max(w.x, w.z) ? p.xz : (w.x > w.z ? p.zy : p.xy);
    return texture(uDetTex, vec3(uv, layer)).rgb;
  #endif
}
vec3 detPerturb(vec3 surf_pos, vec3 surf_norm, vec2 dHdxy, float faceDir) {
  vec3 vSigmaX = dFdx(surf_pos);
  vec3 vSigmaY = dFdy(surf_pos);
  vec3 R1 = cross(vSigmaY, surf_norm);
  vec3 R2 = cross(surf_norm, vSigmaX);
  float fDet = dot(vSigmaX, R1) * faceDir;
  vec3 vGrad = sign(fDet) * (dHdxy.x * R1 + dHdxy.y * R2);
  return normalize(abs(fDet) * surf_norm - vGrad);
}`;

const FRAG_COLOR = /* glsl */ `
{
  vec3 dn = normalize(vDetN);
  vec3 dw = pow(abs(dn), vec3(4.0));
  dw /= (dw.x + dw.y + dw.z);
  int dc = detClass(diffuseColor.rgb, dn.y);
  float dist = length(vViewPosition);
  detA = uDetAmt[dc] * uDetGlobal * (1.0 - 0.55 * smoothstep(25.0, 90.0, dist));
  vec3 dt = detSample(vDetP / uDetScale[dc], uDetLayer[dc], dw);
  diffuseColor.rgb *= mix(1.0, dt.g * 2.0, detA);
  detH = dt.r;
  detR = dt.b;
  #if DET_LEVEL >= 3
    // big soft patches so wide ground never looks like one flat colour
    float macro = texture(uDetTex, vec3(vDetW.xz / 37.0, 11.0)).g;
    diffuseColor.rgb *= 1.0 + (macro - 0.5) * 2.0 * uDetMacro * uDetGlobal;
    // drifting cloud shadows on upward faces
    if (uDetCloud > 0.0) {
      vec2 cp = (vDetW.xz + vec2(uDetTime * 1.3, uDetTime * 0.6)) / 46.0;
      float cl = texture(uDetTex, vec3(cp, 1.0)).r * 0.6 + texture(uDetTex, vec3(cp * 0.43 + 0.3, 3.0)).r * 0.6;
      cl = smoothstep(0.62, 0.78, cl);
      diffuseColor.rgb *= 1.0 - cl * uDetCloud * smoothstep(0.2, 0.7, dn.y);
    }
  #endif
}`;

const FRAG_ROUGH = /* glsl */ `
roughnessFactor = clamp(roughnessFactor * (1.0 + (detR - 0.5) * 0.9 * detA), 0.04, 1.0);`;

const FRAG_NORMAL = /* glsl */ `
#if DET_LEVEL >= 2
{
  float bumpFade = 1.0 - smoothstep(18.0, 60.0, length(vViewPosition));
  vec2 dHdxy = vec2(dFdx(detH), dFdy(detH)) * uDetBump * detA * bumpFade;
  normal = detPerturb(-vViewPosition, normal, dHdxy, faceDirection);
}
#endif`;

const patched = new WeakSet<THREE.Material>();

function wants(m: THREE.Material): m is THREE.MeshStandardMaterial {
  const s = m as THREE.MeshStandardMaterial;
  if (!s.isMeshStandardMaterial || patched.has(m)) return false;
  if (m.userData.noDetail) return false;
  // shaders someone already customised (the sea), see-through things and glowing things stay as they are
  if (s.onBeforeCompile && s.onBeforeCompile.toString().length > 40 && !(s.onBeforeCompile as any).__det) return false;
  if (s.transparent && s.opacity < 0.95) return false;
  if (s.emissive && s.emissiveIntensity > 0.5 && s.emissive.getHex() !== 0) return false;
  // painted icons (space faces, signs) keep their clean look
  if (s.map && (s.map as THREE.CanvasTexture).isCanvasTexture && s.map.repeat.x === 1 && s.map.repeat.y === 1) return false;
  return true;
}

function patch(m: THREE.MeshStandardMaterial, level: number): void {
  patched.add(m);
  const prev = m.onBeforeCompile;
  const fn = (sh: THREE.WebGLProgramParametersWithUniforms, r: THREE.WebGLRenderer) => {
    prev?.call(m, sh, r);
    if (!loadedSize) return;
    Object.assign(sh.uniforms, uniforms);
    sh.defines = { ...(sh.defines ?? {}), DET_LEVEL: level };
    sh.vertexShader = sh.vertexShader
      .replace('#include <common>', '#include <common>' + VERT_HEAD)
      .replace('#include <begin_vertex>', '#include <begin_vertex>' + VERT_BODY);
    sh.fragmentShader = sh.fragmentShader
      .replace('#include <common>', '#include <common>' + FRAG_HEAD)
      .replace('#include <color_fragment>', '#include <color_fragment>' + FRAG_COLOR)
      .replace('#include <roughnessmap_fragment>', '#include <roughnessmap_fragment>' + FRAG_ROUGH)
      .replace('#include <normal_fragment_maps>', '#include <normal_fragment_maps>' + FRAG_NORMAL);
  };
  (fn as any).__det = true;
  m.onBeforeCompile = fn;
  const prevKey = m.customProgramCacheKey.bind(m);
  m.customProgramCacheKey = () => prevKey() + '|det' + (loadedSize ? level : 0);
  m.needsUpdate = true;
}

/**
 * Give every eligible material in `root` the surface detail. Cheap to call again: materials are
 * only patched once (the patch is shared by every scene that uses the same Kenney model).
 */
export function detailTree(root: THREE.Object3D): void {
  const level = gfx().surface;
  if (level === 0 || !loadedSize) return;
  const visit = (o: THREE.Object3D) => {
    if (o.userData.noDetail) return;
    const mesh = o as THREE.Mesh;
    if (mesh.isMesh && !(mesh as THREE.SkinnedMesh).isSkinnedMesh) {
      const mats = Array.isArray(mesh.material) ? mesh.material : [mesh.material];
      for (const m of mats) if (m && wants(m)) patch(m, level);
    }
    for (const c of o.children) visit(c);
  };
  visit(root);
}

/** True once textures are in (scenes built before that get patched on the next sweep). */
export const detailReady = (): boolean => loadedSize > 0;
