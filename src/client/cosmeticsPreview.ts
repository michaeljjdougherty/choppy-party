import * as THREE from 'three';
import { RoomEnvironment } from 'three/examples/jsm/environments/RoomEnvironment.js';
import { preloadAll } from './three/assets';
import { FOLKS, FolkModel } from './three/folks';
import { CATALOG, applyLook, DEFAULT_LOOK, type Category } from './three/cosmetics';

/** Dev page: every cosmetic on a crew member, in a grid. ?cat=hat|shirt|acc&page=0&view=front|back|side */
const q = new URLSearchParams(location.search);
const cat = (q.get('cat') ?? 'hat') as Category;
const page = Number(q.get('page') ?? 0);
const per = 8;
const viewAng = { front: 0.35, back: Math.PI + 0.35, side: Math.PI / 2 } [q.get('view') ?? 'front'] ?? 0.35;
const W = 1600, Hh = 900;
const cv = document.getElementById('c') as HTMLCanvasElement;
const r = new THREE.WebGLRenderer({ canvas: cv, antialias: true, preserveDrawingBuffer: true });
r.setSize(W, Hh);
r.shadowMap.enabled = true;
r.toneMapping = THREE.ACESFilmicToneMapping;
r.outputColorSpace = THREE.SRGBColorSpace;
const pm = new THREE.PMREMGenerator(r);
const scene = new THREE.Scene();
scene.background = new THREE.Color('#6a5acd');
scene.environment = pm.fromScene(new RoomEnvironment(), 0.04).texture;
scene.environmentIntensity = 0.5;
scene.add(new THREE.HemisphereLight('#ffffff', '#806040', 0.9));
const sun = new THREE.DirectionalLight('#fff4dc', 2);
sun.position.set(5, 10, 8);
scene.add(sun);
const cam = new THREE.PerspectiveCamera(30, W / Hh, 0.1, 200);
cam.position.set(0, 3, 21);
cam.lookAt(0, 0.6, 0);
cam.updateMatrixWorld();
const colors = ['#b06cff', '#ff7bd5', '#ffd23f', '#2ee6d6', '#ff9f1c', '#4cd97b', '#3fa9f5', '#f4f1e8', '#9a7b5f', '#ff5a5f'];
const labels: { name: string; x: number; y: number }[] = [];
const models: FolkModel[] = [];
await preloadAll(() => {});
const items = CATALOG[cat].slice(page * per, page * per + per);
items.forEach((it, i) => {
  const spec = FOLKS[i % FOLKS.length];
  const m = new FolkModel(spec, colors[i % colors.length], 1);
  applyLook(m, { ...DEFAULT_LOOK, [cat]: it.id });
  const col = i % 4, row = Math.floor(i / 4);
  m.group.position.set((col - 1.5) * 3.6, row ? -3.2 : 1.9, 0);
  m.group.rotation.y = viewAng;
  scene.add(m.group);
  models.push(m);
  const v = m.group.position.clone().setY(m.group.position.y - 0.2).project(cam);
  labels.push({ name: it.name, x: (v.x + 1) * W / 2, y: (1 - v.y) * Hh / 2 + 24 });
});
for (const m of models) m.update(0.016, 1, {});
r.render(scene, cam);
const ov = document.createElement('canvas');
ov.width = W; ov.height = Hh;
const ctx = ov.getContext('2d')!;
ctx.drawImage(cv, 0, 0);
ctx.font = 'bold 22px sans-serif';
ctx.textAlign = 'center';
ctx.fillStyle = '#fff';
for (const l of labels) ctx.fillText(l.name, l.x, l.y);
document.body.replaceChildren(ov);
(window as any).done = true;
