import * as THREE from 'three';
import { gfx } from './quality';

/**
 * Surface detail for every material in the game, without touching a single view.
 *
 * The Kenney models are flat colours (or one small colour atlas), which reads as "cheap" up close.
 * This injects a few lines into each MeshStandardMaterial: it looks at the colour of every pixel
 * (after the material's own map and vertex colours), decides what that pixel probably is (green on
 * top = grass, brown = wood, grey = stone or metal, white = snow or tiles...) and lays a matching
 * tileable texture over it, projected tri-planar so no model needs UVs. Each texture holds height
 * (for bump lighting), albedo detail and roughness variation. The theme of the current view decides
 * which texture each colour family gets (grey is cobblestone in a village, metal plating in space).
 *
 * The textures are our own, generated by tools/gentex.py (CC0). Players and anything marked
 * `userData.noDetail` are left alone.
 */

export const LAYERS = ['grass', 'dirt', 'cobble', 'rock', 'wood', 'metal', 'snow', 'tiles', 'brick', 'bark', 'fabric', 'toy', 'sand'] as const;
export type Layer = (typeof LAYERS)[number];
const L = (n: Layer) => LAYERS.indexOf(n);

/** Colour families a pixel can fall in. */
export const CLASSES = ['greenUp', 'greenSide', 'brown', 'tanUp', 'tanSide', 'greyUp', 'greySide', 'whiteUp', 'whiteSide', 'other', 'dark'] as const;
export type ColourClass = (typeof CLASSES)[number];

/** [layer, strength 0..1, world units per texture tile] */
export type Rule = [Layer, number, number];
export type Palette = Record<ColourClass, Rule>;

